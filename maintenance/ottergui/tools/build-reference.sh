#!/usr/bin/env bash
# Rebuild references/ from local checkouts.
# usage: tools/build-reference.sh <fork checkout> <OtterGuiInternal checkout> <upstream ref> [<artisan pin ref>]
#   <fork checkout>      Limiana/OtterGui, checked out at the commit to pin, with the upstream
#                        commit (and the Artisan pin, if given) fetched into the same repository
#   <internal checkout>  Ottermandias/OtterGuiInternal, checked out at the commit the fork pins
#   <upstream ref>       Ottermandias/OtterGui commit to compare against
set -euo pipefail
FORK=$(realpath "$1"); INTERNAL=$(realpath "$2"); UPSTREAM=$3; ARTISAN=${4:-}
ROOT=$(cd "$(dirname "$0")/.." && pwd)
REF="$ROOT/../../skills/ottergui/references"
SIGS=$(mktemp -d)/sigs
go -C "$ROOT" build -o "$SIGS" ./tools/sigs
keep='\.cs$|(^|/)LICENSE$|\.csproj$|\.sln$|^\.gitmodules$|^packages\.lock\.json$'

rm -rf "$REF/src"; mkdir -p "$REF/src/OtterGuiInternal"
( cd "$FORK" && git ls-files | grep -E "$keep" | grep -v '^OtterGuiInternal$' ) | while IFS= read -r f; do
  mkdir -p "$REF/src/$(dirname "$f")"; cp "$FORK/$f" "$REF/src/$f"
done
( cd "$INTERNAL" && git ls-files | grep -E "$keep" ) | while IFS= read -r f; do
  mkdir -p "$REF/src/OtterGuiInternal/$(dirname "$f")"; cp "$INTERNAL/$f" "$REF/src/OtterGuiInternal/$f"
done

( cd "$REF/src" && find . -type f | sed 's|^\./||' | LC_ALL=C sort ) > "$REF/manifest.txt"

# path:line: declaration for every public/protected declaration (multi-line parameter lists joined)
( cd "$REF/src" && find . -name '*.cs' | sed 's|^\./||' | LC_ALL=C sort | xargs "$SIGS" ) > "$REF/api-index.txt"
grep -E ': public ((static|sealed|abstract|unsafe|readonly|partial|ref|record) )*(class|interface|struct|enum|record|delegate) ' \
  "$REF/api-index.txt" > "$REF/public-types.txt" || true

( cd "$FORK"
  git diff "$UPSTREAM" HEAD -- . ':!OtterGuiInternal' > "$REF/upstream-to-fork.diff"
  git diff "$UPSTREAM" HEAD -- OtterGuiInternal >> "$REF/upstream-to-fork.diff"
  if [ -n "$ARTISAN" ]; then
    git diff HEAD "$ARTISAN" -- . ':!OtterGuiInternal' ':!.editorconfig' > "$REF/fork-to-artisan-pin.diff"
    git diff HEAD "$ARTISAN" -- OtterGuiInternal >> "$REF/fork-to-artisan-pin.diff"
  fi
  {
    echo "# Fork versus upstream: generated summary"
    echo
    echo "Generated by tools/build-reference.sh. Interpretation: topic-fork-delta.md."
    echo "Raw diffs: references/upstream-to-fork.diff, references/fork-to-artisan-pin.diff."
    echo
    echo "## Commits"
    echo
    echo '```'
    echo "fork      $(git log -1 --format='%H %cI %s' HEAD)"
    echo "upstream  $(git log -1 --format='%H %cI %s' "$UPSTREAM")"
    echo "mergebase $(git log -1 --format='%H %cI %s' "$(git merge-base HEAD "$UPSTREAM")")"
    [ -n "$ARTISAN" ] && echo "artisan   $(git log -1 --format='%H %cI %s' "$ARTISAN")"
    echo '```'
    echo
    echo "## Files changed, upstream -> fork"
    echo
    echo '```'
    git diff --stat=100 "$UPSTREAM" HEAD
    echo '```'
    echo
    echo "## Commits in the fork that are not in upstream"
    echo
    echo '```'
    git log --format='%h %cs %s' "$UPSTREAM"..HEAD
    echo '```'
    echo
    echo "## Commits in upstream that are not in the fork"
    echo
    echo '```'
    git log --format='%h %cs %s' HEAD.."$UPSTREAM"
    echo '```'
    echo
    echo "## Files added or removed, upstream -> fork"
    echo
    echo '```'
    git diff --name-status --diff-filter=ADR "$UPSTREAM" HEAD
    echo '(end of list; empty means none)'
    echo '```'
    if [ -n "$ARTISAN" ]; then
      echo
      echo "## Files changed, upstream -> Artisan pin"
      echo
      echo '```'
      git diff --stat=100 "$UPSTREAM" "$ARTISAN"
      echo '```'
      echo
      echo "## Files changed, fork -> Artisan pin"
      echo
      echo '```'
      git diff --stat=100 HEAD "$ARTISAN"
      echo '```'
      echo
      echo "## Commits in the Artisan pin that are not in upstream"
      echo
      echo '```'
      git log --format='%h %cs %s' "$UPSTREAM".."$ARTISAN"
      echo '```'
    fi
  } > "$REF/fork-vs-upstream.md"
  {
    echo "Limiana/OtterGui            $(git log -1 --format='%H %cI' HEAD)"
    echo "Ottermandias/OtterGui       $(git log -1 --format='%H %cI' "$UPSTREAM")"
    [ -n "$ARTISAN" ] && echo "Artisan pin (Taurenkey)     $(git log -1 --format='%H %cI' "$ARTISAN")"
    echo "OtterGuiInternal (fork pin) $(git -C "$INTERNAL" log -1 --format='%H %cI' HEAD)"
  } > "$REF/VERSIONS.txt"
)
wc -l "$REF/manifest.txt" "$REF/api-index.txt" "$REF/public-types.txt"
cat "$REF/VERSIONS.txt"
